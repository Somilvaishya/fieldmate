"""A link a rep sends a party so they can look at the range at their own prices.

**This is the only thing in the app that answers to somebody with no login.** Everything else -
the PWA, the portal, Desk - is behind a session. A share link is a URL in a WhatsApp message, and
whoever holds it is whoever was forwarded it, so the whole design is about keeping what it can
reveal as small as the job allows:

- the token is generated by the server, never chosen, and long enough not to be guessed;
- it carries **one party's** prices and nothing about any other party;
- it expires, because a quotation that never expires is a price somebody holds you to next year;
- it can be switched off, which is the only way a URL is ever taken back;
- it can be capped by opens, because a link forwarded round a market is still one link and this
  is the only thing that notices.

What it deliberately does **not** show: credit, outstanding, anybody's order history, any other
party's price, or anything about the rep beyond their name.
"""

from __future__ import annotations

import frappe
from frappe.model.document import Document
from frappe.utils import add_days, cint, getdate, now_datetime, nowdate

# How long a link lives when nobody says. Short on purpose: a share is a conversation a rep is
# having this week, and a price that outlives the conversation is a price being quoted by nobody.
DEFAULT_DAYS = 30

# Long enough that guessing is not a strategy. `frappe.generate_hash` is urandom-backed.
TOKEN_LENGTH = 32


class FieldMateShareLink(Document):
	def before_insert(self):
		self.token = frappe.generate_hash(length=TOKEN_LENGTH)

	def validate(self):
		self.settle_the_party()
		self.check_the_catalogue()
		self.default_the_window()
		self.resolve_the_price_list()

	def settle_the_party(self):
		"""Exactly one party, and `party_type` agreeing with it.

		The same rule as FieldMate Order, for the same reason: a link that names both or neither
		has no answer to "whose prices are these", which is the only question it exists to
		answer.
		"""
		if self.party_type == "Customer":
			self.outlet = None
			if not self.customer:
				frappe.throw(frappe._("Which customer is this link for?"))
		else:
			self.customer = None
			if not self.outlet:
				frappe.throw(frappe._("Which shop is this link for?"))

	def check_the_catalogue(self):
		"""Only a showcase can be shared.

		An ordinary catalogue is an internal list - it carries focus flags, minimum order
		quantities and notes written for a rep. Putting one in front of a customer is not a
		feature, it is a leak, so the catalogue has to say out loud that it was written to be
		read.
		"""
		if not self.catalogue:
			return
		if not cint(frappe.db.get_value("FieldMate Product Catalogue", self.catalogue,
		                                "is_showcase")):
			frappe.throw(frappe._(
				"{0} is not a showcase, so it cannot be shared. Tick Showcase on the catalogue "
				"if it was written to be read by a customer."
			).format(self.catalogue))

	def default_the_window(self):
		if not self.valid_from:
			self.valid_from = nowdate()
		if not self.valid_to:
			self.valid_to = add_days(self.valid_from, DEFAULT_DAYS)
		if getdate(self.valid_to) < getdate(self.valid_from):
			frappe.throw(frappe._("This link would expire before it starts."))

	def resolve_the_price_list(self):
		"""Fix the price list when the link is made, and never move it.

		Resolved through the ordinary chain, so a share quotes exactly what an order would. Fixed
		rather than resolved on each open because a party reading a price on Tuesday and being
		quoted another on Wednesday is the argument this field exists to prevent - and because a
		public page should not be running the pricing chain on every request.
		"""
		if self.price_list:
			return

		from fieldmate.services import channel as channel_service

		party = self.customer if self.party_type == "Customer" else self.outlet
		answer = channel_service.resolve(party, self.party_type, self.field_user)
		self.price_list = answer.get("price_list")

		if not self.price_list:
			frappe.throw(frappe._(
				"There is no price list for {0}, so there is nothing to show them. {1}"
			).format(party, answer.get("reason") or ""))

	def is_live(self, on=None) -> tuple[bool, str]:
		"""Can this link be opened right now, and if not, what does the visitor get told?

		Returned rather than thrown, and the reasons are deliberately vague to the visitor: a
		page that says "this link expired on the 3rd" to anybody who holds a URL is telling a
		stranger something about a conversation they were not part of.
		"""
		on = getdate(on or nowdate())

		if not cint(self.is_active):
			return False, frappe._("This link is no longer available.")
		if self.valid_from and on < getdate(self.valid_from):
			return False, frappe._("This link is not open yet.")
		if self.valid_to and on > getdate(self.valid_to):
			return False, frappe._("This link has expired. Ask for a new one.")
		if cint(self.max_views) and cint(self.view_count) >= cint(self.max_views):
			return False, frappe._("This link is no longer available.")

		return True, ""

	def note_an_open(self, ip: str | None = None) -> None:
		"""Record that somebody looked, without a save.

		`db_set` and not `save`: a public page must not run document validation, fire hooks or
		take a document lock on every request. Counting a view is not a change to the link.
		"""
		now = now_datetime()
		self.db_set("view_count", cint(self.view_count) + 1, update_modified=False)
		self.db_set("last_opened", now, update_modified=False)
		if not self.first_opened:
			self.db_set("first_opened", now, update_modified=False)
		if ip:
			self.db_set("last_seen_ip", ip[:140], update_modified=False)
